        function logScreenshot(type) {
            $.ajax({
                url: '',
                type: 'POST',
                data: {
                    pagelink: window.location.href,
                    type: type,
                    device: navigator.userAgent
                },
                success: function(response) {
                    console.log('Screenshot logged');
                }
            });
